#!/usr/bin/env bash
# Compile the contracts and emit ABIs, bytecode, and a standard-json input
# suitable for one-click source verification on Blockscout.
set -euo pipefail
cd "$(dirname "$0")/.."

SOLC="${SOLC:-solc}"
VERSION="$("$SOLC" --version | sed -n 's/.*Version: \([0-9.]*\).*/\1/p')"
[ "$VERSION" = "0.8.24" ] || { echo "need solc 0.8.24, found ${VERSION:-none}" >&2; exit 1; }

mkdir -p contract/abi contract/build
python3 - "$SOLC" <<'PY'
import json, subprocess, sys
from pathlib import Path

solc = sys.argv[1]
sources = ["GenesisL1APIRegistry.sol", "GenesisL1RegistryLens.sol"]
standard = {
    "language": "Solidity",
    "sources": {name: {"content": Path("contract", name).read_text()} for name in sources},
    "settings": {
        "optimizer": {"enabled": True, "runs": 200},
        "viaIR": True,
        "evmVersion": "paris",
        "outputSelection": {"*": {"*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"]}},
    },
}
Path("contract/build/standard-input.json").write_text(json.dumps(standard, indent=2))

result = json.loads(subprocess.run([solc, "--standard-json"], input=json.dumps(standard),
                                   capture_output=True, text=True).stdout)
fatal = [e for e in result.get("errors", []) if e["severity"] == "error"]
if fatal:
    sys.exit("\n".join(e["formattedMessage"] for e in fatal))

for source, contracts in result["contracts"].items():
    for name, artifact in contracts.items():
        if not artifact["abi"] and not artifact["evm"]["bytecode"]["object"]:
            continue
        Path("contract/abi", f"{name}.json").write_text(json.dumps(artifact["abi"], indent=2))
        Path("contract/build", f"{name}.bin").write_text(artifact["evm"]["bytecode"]["object"])
        size = len(artifact["evm"]["deployedBytecode"]["object"]) // 2
        if size:
            print(f"  {name:26s} {size:6d} bytes runtime  ({24576 - size} under EIP-170)")

# The browser reads the ABI the compiler produced. Nothing is transcribed by
# hand, so the interface cannot drift from the deployed contract.
bundle = {
    "registry": json.loads(Path("contract/abi/GenesisL1APIRegistry.json").read_text()),
    "lens": json.loads(Path("contract/abi/GenesisL1RegistryLens.json").read_text()),
}
Path("web/vendor/abi.js").write_text(
    "/* Generated by scripts/build.sh from the solc output. Do not edit. */\n"
    "window.GENESIS_ABI=" + json.dumps(bundle, separators=(",", ":")) + ";\n"
)
print(f"  {'web/vendor/abi.js':26s} {Path('web/vendor/abi.js').stat().st_size:6d} bytes")
PY
echo "artifacts written to contract/abi and contract/build"
